/// Historical runtime-terminal profile from the reviewed KONE terminal manual.
/// It is not live-validated on the target CPU561. The distinct 115200 servicing
/// profile is intentionally not constructible through this connector.
#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct LceRuntimeTerminalProfile {
    baud: u32,
    data_bits: LceDataBits,
    parity: LceParity,
    stop_bits: LceStopBits,
}

impl LceRuntimeTerminalProfile {
    pub const fn historical_9600_8n1() -> Self {
        Self {
            baud: 9600,
            data_bits: LceDataBits::Eight,
            parity: LceParity::None,
            stop_bits: LceStopBits::One,
        }
    }

    pub const fn baud(self) -> u32 {
        self.baud
    }

    pub const fn data_bits(self) -> LceDataBits {
        self.data_bits
    }

    pub const fn parity(self) -> LceParity {
        self.parity
    }

    pub const fn stop_bits(self) -> LceStopBits {
        self.stop_bits
    }
}

#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize)]
